/** a UI word in `lang` with {placeholders} filled; English when the key is missing in `lang`, the key itself when missing everywhere */
export function ui(lang, key, args) {
  const table = STRINGS[lang] || STRINGS.en;
  let s = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : (STRINGS.en[key] !== undefined ? STRINGS.en[key] : key);
  if (args) s = s.replace(/\{(\w+)\}/g, (m, k) => (args[k] !== undefined && args[k] !== null ? String(args[k]) : m));
  return s;
}

/** the language to start in: the saved choice (the only thing the app keeps), else the browser's language */
export function initialLang(saved, navigatorLang) {
  if (LANGS.includes(saved)) return saved;
  return /^es\b/i.test(String(navigatorLang || '')) ? 'es' : 'en';
}
